CREATE EXTENSION IF NOT EXISTS pgcrypto;  -- crypt()/gen_salt() para las contraseñas de los datos iniciales

-- Modelo de datos v3.8 · EdRev Cesmag · Sistema de gestión editorial
-- PostgreSQL 14 o superior.
-- Orden de creación = orden topológico (sin referencias circulares).
-- Los valores de configuración (umbral de coincidencias, intentos, máximo de pares,
-- días de espera) y las credenciales van en variables de entorno del servidor.
 
-- 1. Tablas independientes
CREATE TABLE revista (
  id_revista       SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre           VARCHAR(150) NOT NULL UNIQUE,
  correo_remitente VARCHAR(150) NOT NULL CHECK (correo_remitente = lower(correo_remitente))
);
 
CREATE TABLE usuario (
  id_usuario      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre          VARCHAR(150) NOT NULL,
  correo          VARCHAR(150) NOT NULL UNIQUE CHECK (correo = lower(correo)),
  contrasena_hash VARCHAR(255) NOT NULL,
  rol             VARCHAR(13)  NOT NULL CHECK (rol IN ('administrador','auxiliar')),
  activo          BOOLEAN      NOT NULL DEFAULT TRUE,
  ultimo_ingreso  TIMESTAMPTZ
);
 
CREATE TABLE autor (
  id_autor INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre   VARCHAR(200) NOT NULL,
  orcid    VARCHAR(19)  UNIQUE
             CHECK (orcid ~ '^[0-9]{4}-[0-9]{4}-[0-9]{4}-[0-9]{3}[0-9X]$'),
  correo   VARCHAR(150)
);
 
CREATE TABLE plantilla (            -- cada revista tiene las suyas
  id_plantilla SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_revista   SMALLINT     NOT NULL REFERENCES revista ON DELETE RESTRICT,
  nombre       VARCHAR(80)  NOT NULL,
  tipo         VARCHAR(14)  NOT NULL
                 CHECK (tipo IN ('invitacion','agradecimiento','constancia')),
  asunto       VARCHAR(200),
  cuerpo       TEXT         NOT NULL,
  fondo_pdf    BYTEA,       -- membrete, diseño y firma de la constancia
  en_uso       BOOLEAN      NOT NULL DEFAULT FALSE,
  CONSTRAINT uq_plantilla_nombre UNIQUE (id_revista, nombre),
  CONSTRAINT ck_asunto_solo_correos CHECK ((tipo = 'constancia') = (asunto IS NULL)),
  CONSTRAINT ck_fondo_solo_constancia CHECK ((tipo = 'constancia') = (fondo_pdf IS NOT NULL))
);
 
-- 2. Dependen de revista o de usuario
CREATE TABLE articulo (
  id_articulo              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_revista               SMALLINT     NOT NULL REFERENCES revista ON DELETE RESTRICT,
  numero_ojs               VARCHAR(20)  NOT NULL,
  titulo                   VARCHAR(500) NOT NULL,
  tipo                     VARCHAR(13)  -- nulo solo en migrados cuyo texto no encajó (RF-44)
                             CHECK (tipo IN ('investigacion','reflexion','revision')),
  fecha_postulacion        DATE,
  porcentaje_coincidencias NUMERIC(5,2) CHECK (porcentaje_coincidencias BETWEEN 0 AND 100),
  porcentaje_ia            NUMERIC(5,2) CHECK (porcentaje_ia BETWEEN 0 AND 100),
  estado                   VARCHAR(13)  NOT NULL DEFAULT 'postulado'
                             CHECK (estado IN ('postulado','en-revision','en-evaluacion',
                                               'aprobado','rechazado','archivado')),
  volumen                  SMALLINT     CHECK (volumen > 0),
  numero                   SMALLINT     CHECK (numero > 0),
  CONSTRAINT ck_publicacion_completa CHECK ((volumen IS NULL) = (numero IS NULL))
);
 
CREATE TABLE par_evaluador (
  id_par         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_revista     SMALLINT     NOT NULL REFERENCES revista ON DELETE RESTRICT,
  nombre         VARCHAR(200) NOT NULL,
  correo         VARCHAR(150) CHECK (correo = lower(correo)),
  universidad    VARCHAR(200),
  area           VARCHAR(150),
  profesion      VARCHAR(150),  -- extensión: «nombre del par con su profesión» en la invitación (RF-25)
  motivo_bloqueo VARCHAR(13)  CHECK (motivo_bloqueo IN ('sin-respuesta','no-participa')),
  fecha_bloqueo  DATE,
  UNIQUE (id_revista, correo),
  CONSTRAINT ck_bloqueo_completo CHECK ((motivo_bloqueo IS NULL) = (fecha_bloqueo IS NULL))
);
 
CREATE TABLE auditoria (
  id_auditoria   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario     INTEGER     REFERENCES usuario ON DELETE RESTRICT,  -- NULL: el sistema
  tabla_afectada VARCHAR(40) NOT NULL,   -- en qué tabla está la fila cambiada
  id_registro    VARCHAR(40) NOT NULL,   -- número de esa fila dentro de la tabla
  accion         VARCHAR(12) NOT NULL CHECK (accion IN ('registro','edicion','revision',
                   'asignacion','respuesta','entrega','constancia','envio','fallo','bloqueo',
                   'desbloqueo','traslado','cierre','reapertura','migracion','eliminacion')),  -- = filtro de la página
  fecha          TIMESTAMPTZ NOT NULL DEFAULT now(),
  detalle        JSONB       -- incluye {"revista": n, "articulo": n} cuando aplica
);
 
-- 3. Dependen de articulo, autor o par_evaluador
CREATE TABLE articulo_autor (
  id_articulo INTEGER      NOT NULL REFERENCES articulo ON DELETE CASCADE,
  id_autor    INTEGER      NOT NULL REFERENCES autor    ON DELETE RESTRICT,
  orden       SMALLINT     NOT NULL CHECK (orden BETWEEN 1 AND 7),
  filiacion   VARCHAR(200),
  pais        VARCHAR(80),
  PRIMARY KEY (id_articulo, id_autor),
  UNIQUE (id_articulo, orden)
);
 
CREATE TABLE evaluacion (
  id_evaluacion      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_articulo        INTEGER     NOT NULL REFERENCES articulo      ON DELETE RESTRICT,
  id_par             INTEGER     NOT NULL REFERENCES par_evaluador ON DELETE RESTRICT,
  estado_par         VARCHAR(13) NOT NULL DEFAULT 'invitado'
                       CHECK (estado_par IN ('invitado','acepto','no-acepto',
                                             'sin-respuesta','entrego')),
  concepto           VARCHAR(18) CHECK (concepto IN ('publicable','con-modificaciones',
                                                     'no-publicable','pendiente-formato')),
  es_desempate       BOOLEAN     NOT NULL DEFAULT FALSE,
  fecha_asignacion   TIMESTAMPTZ NOT NULL DEFAULT now(),
  fecha_evaluacion   DATE,
  constancia_emitida BOOLEAN     NOT NULL DEFAULT FALSE,
  UNIQUE (id_articulo, id_par),
  CONSTRAINT ck_datos_de_entrega CHECK (estado_par = 'entrego' OR
             (concepto IS NULL AND fecha_evaluacion IS NULL AND NOT constancia_emitida))
);
 
CREATE TABLE revision_inicial_comite (            -- cada ronda de la revisión inicial del comité editorial
  id_revision    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_articulo    INTEGER     NOT NULL REFERENCES articulo ON DELETE CASCADE,
  id_usuario     INTEGER     NOT NULL REFERENCES usuario  ON DELETE RESTRICT,
  resultado      VARCHAR(9)  NOT NULL CHECK (resultado IN ('aprobado','rechazado','ajustes')),
  observacion    TEXT,
  fecha          TIMESTAMPTZ NOT NULL DEFAULT now()
);
 
-- 4. Depende de evaluacion
CREATE TABLE correo (
  id_correo     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_evaluacion INTEGER      NOT NULL REFERENCES evaluacion ON DELETE RESTRICT,
  tipo          VARCHAR(14)  NOT NULL CHECK (tipo IN ('invitacion','agradecimiento','constancia')),  -- «constancia»: solo la constancia, sin el texto de agradecimiento
  destinatario  VARCHAR(150) NOT NULL,
  fecha_envio   TIMESTAMPTZ  NOT NULL DEFAULT now(),
  resultado     VARCHAR(8)   NOT NULL DEFAULT 'en-cola'
                  CHECK (resultado IN ('en-cola','enviado','rebotado','fallido'))
);
 
-- 4b. Registros migrados del Excel cuyo texto libre no encajó en las listas (RF-44, extensión)
CREATE TABLE por_corregir (
  id_registro   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_revista    SMALLINT    NOT NULL REFERENCES revista ON DELETE RESTRICT,
  campo         VARCHAR(15) NOT NULL
                  CHECK (campo IN ('tipo-articulo','estado-articulo','concepto','correo-par')),
  valor_excel   TEXT        NOT NULL DEFAULT '',   -- lo que decía el Excel (vacío si no lo traía)
  id_articulo   INTEGER REFERENCES articulo      ON DELETE CASCADE,
  id_evaluacion INTEGER REFERENCES evaluacion    ON DELETE CASCADE,
  id_par        INTEGER REFERENCES par_evaluador ON DELETE CASCADE
);

-- 5. Regla de la única relación cerrada: el par y el artículo son de la misma revista
CREATE FUNCTION fn_evaluacion_misma_revista() RETURNS trigger AS $$
BEGIN
  IF (SELECT id_revista FROM articulo WHERE id_articulo = NEW.id_articulo)
     <> (SELECT id_revista FROM par_evaluador WHERE id_par = NEW.id_par) THEN
    RAISE EXCEPTION 'El par % no pertenece a la revista del artículo %',
                    NEW.id_par, NEW.id_articulo;
  END IF;
  RETURN NEW;
END $$ LANGUAGE plpgsql;
 
CREATE TRIGGER tg_evaluacion_misma_revista
  BEFORE INSERT OR UPDATE OF id_articulo, id_par ON evaluacion
  FOR EACH ROW EXECUTE FUNCTION fn_evaluacion_misma_revista();
 
-- El artículo solo cambia de revista mientras está en la revisión inicial del comité:
-- sin una ronda aprobada, sin pares asignados y en estado Postulado o En revisión.
CREATE FUNCTION fn_articulo_cambio_revista() RETURNS trigger AS $$
BEGIN
  IF NEW.id_revista <> OLD.id_revista AND (
       OLD.estado NOT IN ('postulado','en-revision')
       OR EXISTS (SELECT 1 FROM revision_inicial_comite r
                   WHERE r.id_articulo = OLD.id_articulo AND r.resultado = 'aprobado')
       OR EXISTS (SELECT 1 FROM evaluacion e WHERE e.id_articulo = OLD.id_articulo)) THEN
    RAISE EXCEPTION 'El artículo % ya salió de la revisión del comité: no puede cambiar de revista',
                    OLD.id_articulo;
  END IF;
  RETURN NEW;
END $$ LANGUAGE plpgsql;
 
CREATE TRIGGER tg_articulo_cambio_revista
  BEFORE UPDATE OF id_revista ON articulo
  FOR EACH ROW EXECUTE FUNCTION fn_articulo_cambio_revista();
 
