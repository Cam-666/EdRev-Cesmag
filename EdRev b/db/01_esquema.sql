CREATE EXTENSION IF NOT EXISTS pgcrypto;  -- crypt()/gen_salt() para las contraseñas de los datos iniciales

-- PostgreSQL 14 o superior.
-- Las tablas se crean en orden: primero las que no dependen de otras, para no tener referencias circulares.
-- Los valores de configuración (umbral de coincidencias, intentos, máximo de pares, días de espera) y las
-- credenciales no están aquí: van en variables de entorno del servidor (ver .env.example).
 
-- 1. Tablas independientes
CREATE TABLE revista (
  id_revista       SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre           VARCHAR(150) NOT NULL UNIQUE,
  correo_remitente VARCHAR(150) NOT NULL CHECK (correo_remitente = lower(correo_remitente)),
  issn             VARCHAR(20),     -- extensión: va en la constancia como {{issn}}
  indexaciones     VARCHAR(1500)    -- extensión: texto con las indexaciones; va en la constancia como {{indexaciones}}
);
 
CREATE TABLE configuracion (          -- extensión: valores que la Administradora ajusta desde la página
  clave VARCHAR(40) PRIMARY KEY,
  valor TEXT        NOT NULL
);

CREATE TABLE usuario (
  id_usuario      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre          VARCHAR(150) NOT NULL,
  correo          VARCHAR(150) NOT NULL UNIQUE CHECK (correo = lower(correo)),
  contrasena_hash VARCHAR(255) NOT NULL,
  rol             VARCHAR(13)  NOT NULL CHECK (rol IN ('administrador','auxiliar')),
  activo          BOOLEAN      NOT NULL DEFAULT TRUE,
  ultimo_ingreso  TIMESTAMPTZ
);
 
CREATE TABLE autor (
  id_autor INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre   VARCHAR(200) NOT NULL,
  orcid    VARCHAR(19)  UNIQUE
             CHECK (orcid ~ '^[0-9]{4}-[0-9]{4}-[0-9]{4}-[0-9]{3}[0-9X]$'),
  correo   VARCHAR(150),
  filiacion VARCHAR(200),  -- extensión: última filiación conocida (la de cada artículo está en articulo_autor)
  pais      VARCHAR(80)
);
 
CREATE TABLE plantilla (            -- cada revista tiene las suyas
  id_plantilla SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_revista   SMALLINT     NOT NULL REFERENCES revista ON DELETE RESTRICT,
  nombre       VARCHAR(80)  NOT NULL,
  clase        VARCHAR(7)   NOT NULL CHECK (clase IN ('correo','archivo')),
  fin          VARCHAR(14)  NOT NULL CHECK (fin IN ('invitacion','agradecimiento','constancia','mensaje')),  -- para qué sirve; no cambia («mensaje»: se elige al enviar un correo a mano)
  tipo         VARCHAR(14)  CHECK (tipo IN ('invitacion','agradecimiento','constancia')),  -- el fin al que está en uso hoy; NULL si no está en uso
  asunto       VARCHAR(200),
  cuerpo       TEXT         NOT NULL,
  encabezado   BYTEA,       -- imagen del encabezado de la constancia (solo tipo constancia)
  pie          BYTEA,       -- imagen del pie de página de la constancia (solo clase archivo)
  firma        BYTEA,       -- imagen de la firma, donde el texto pone {{firma}}
  CONSTRAINT uq_plantilla_nombre UNIQUE (id_revista, nombre),
  CONSTRAINT ck_asunto_solo_correos CHECK ((clase = 'correo') = (asunto IS NOT NULL)),
  CONSTRAINT ck_imagenes_solo_archivo CHECK (clase = 'archivo' OR (encabezado IS NULL AND pie IS NULL AND firma IS NULL)),  -- el correo no lleva imágenes
  CONSTRAINT ck_fin_de_su_clase CHECK ((fin = 'constancia') = (clase = 'archivo')),
  CONSTRAINT ck_en_uso_es_su_fin CHECK (tipo IS NULL OR tipo = fin)
);
 
-- 2. Dependen de revista o de usuario
CREATE TABLE articulo (
  id_articulo              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_revista               SMALLINT     NOT NULL REFERENCES revista ON DELETE RESTRICT,
  numero_ojs               VARCHAR(20)  NOT NULL,
  titulo                   VARCHAR(500) NOT NULL,
  tipo                     VARCHAR(13)  -- nulo solo en migrados cuyo texto no encajó
                             CHECK (tipo IN ('investigacion','reflexion','revision')),
  fecha_postulacion        DATE,
  porcentaje_coincidencias NUMERIC(5,2) CHECK (porcentaje_coincidencias BETWEEN 0 AND 100),
  porcentaje_ia            NUMERIC(5,2) CHECK (porcentaje_ia BETWEEN 0 AND 100),
  estado                   VARCHAR(13)  NOT NULL DEFAULT 'postulado'
                             CHECK (estado IN ('postulado','en-revision','en-evaluacion',
                                               'aprobado','rechazado','archivado')),
  volumen                  SMALLINT     CHECK (volumen > 0),
  numero                   SMALLINT     CHECK (numero > 0),
  CONSTRAINT ck_publicacion_completa CHECK ((volumen IS NULL) = (numero IS NULL))
);
 
CREATE TABLE par_evaluador (
  id_par         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_revista     SMALLINT     NOT NULL REFERENCES revista ON DELETE RESTRICT,  -- revista donde se registró (informativa): la base de pares es común a las dos
  nombre         VARCHAR(200) NOT NULL,
  correo         VARCHAR(150) CHECK (correo = lower(correo)),
  universidad    VARCHAR(200),
  area           VARCHAR(150),
  profesion      VARCHAR(150),  -- extensión: la invitación dice «nombre del par con su profesión»
  motivo_bloqueo VARCHAR(13)  CHECK (motivo_bloqueo IN ('sin-respuesta','no-participa')),
  fecha_bloqueo  DATE,
  UNIQUE (correo),
  CONSTRAINT ck_bloqueo_completo CHECK ((motivo_bloqueo IS NULL) = (fecha_bloqueo IS NULL))
);
 
CREATE TABLE auditoria (
  id_auditoria   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario     INTEGER     REFERENCES usuario ON DELETE RESTRICT,  -- NULL: el sistema
  tabla_afectada VARCHAR(40) NOT NULL,   -- en qué tabla está la fila cambiada
  id_registro    VARCHAR(40) NOT NULL,   -- número de esa fila dentro de la tabla
  accion         VARCHAR(12) NOT NULL CHECK (accion IN ('registro','edicion','revision',
                   'asignacion','respuesta','entrega','constancia','envio','fallo','bloqueo',
                   'desbloqueo','traslado','cierre','reapertura','migracion','eliminacion')),  -- = filtro de la página
  fecha          TIMESTAMPTZ NOT NULL DEFAULT now(),
  detalle        JSONB       -- incluye {"revista": n, "articulo": n} cuando aplica
);
 
-- 3. Dependen de articulo, autor o par_evaluador
CREATE TABLE articulo_autor (
  id_articulo INTEGER      NOT NULL REFERENCES articulo ON DELETE CASCADE,
  id_autor    INTEGER      NOT NULL REFERENCES autor    ON DELETE RESTRICT,
  orden       SMALLINT     NOT NULL CHECK (orden BETWEEN 1 AND 7),
  filiacion   VARCHAR(200),
  pais        VARCHAR(80),
  PRIMARY KEY (id_articulo, id_autor),
  UNIQUE (id_articulo, orden)
);
 
CREATE TABLE evaluacion (
  id_evaluacion      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_articulo        INTEGER     NOT NULL REFERENCES articulo      ON DELETE RESTRICT,
  id_par             INTEGER     NOT NULL REFERENCES par_evaluador ON DELETE RESTRICT,
  estado_par         VARCHAR(13) NOT NULL DEFAULT 'invitado'
                       CHECK (estado_par IN ('invitado','acepto','no-acepto',
                                             'sin-respuesta','entrego')),
  concepto           VARCHAR(18) CHECK (concepto IN ('publicable','con-modificaciones',
                                                     'no-publicable','pendiente-formato')),
  es_desempate       BOOLEAN     NOT NULL DEFAULT FALSE,
  fecha_asignacion   TIMESTAMPTZ NOT NULL DEFAULT now(),
  fecha_evaluacion   DATE,
  constancia_emitida BOOLEAN     NOT NULL DEFAULT FALSE,
  UNIQUE (id_articulo, id_par),
  CONSTRAINT ck_datos_de_entrega CHECK (estado_par = 'entrego' OR
             (concepto IS NULL AND fecha_evaluacion IS NULL AND NOT constancia_emitida))
);
 
CREATE TABLE revision_inicial_comite (            -- cada ronda de la revisión inicial del comité editorial
  id_revision    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_articulo    INTEGER     NOT NULL REFERENCES articulo ON DELETE CASCADE,
  id_usuario     INTEGER     NOT NULL REFERENCES usuario  ON DELETE RESTRICT,
  resultado      VARCHAR(9)  NOT NULL CHECK (resultado IN ('aprobado','rechazado','ajustes')),
  observacion    TEXT,
  fecha          TIMESTAMPTZ NOT NULL DEFAULT now()
);
 
-- 4. Depende de evaluacion
CREATE TABLE correo (
  id_correo     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_evaluacion INTEGER      NOT NULL REFERENCES evaluacion ON DELETE RESTRICT,
  tipo          VARCHAR(14)  NOT NULL CHECK (tipo IN ('invitacion','agradecimiento','constancia')),  -- «constancia»: solo la constancia, sin el texto de agradecimiento
  destinatario  VARCHAR(150) NOT NULL,
  fecha_envio   TIMESTAMPTZ  NOT NULL DEFAULT now(),
  resultado     VARCHAR(8)   NOT NULL DEFAULT 'en-cola'
                  CHECK (resultado IN ('en-cola','enviado','rebotado','fallido')),
  id_plantilla  SMALLINT     REFERENCES plantilla ON DELETE SET NULL,  -- la plantilla elegida al enviar (NULL: la predeterminada)
  asunto_propio VARCHAR(300),                                         -- asunto y texto editados solo para este envío
  cuerpo_propio TEXT
);
 
-- 4b. Registros migrados del Excel cuyo texto libre no encajó en las listas del sistema
CREATE TABLE por_corregir (
  id_registro   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_revista    SMALLINT    NOT NULL REFERENCES revista ON DELETE RESTRICT,
  campo         VARCHAR(15) NOT NULL
                  CHECK (campo IN ('tipo-articulo','estado-articulo','concepto','correo-par')),
  valor_excel   TEXT        NOT NULL DEFAULT '',   -- lo que decía el Excel (vacío si no lo traía)
  id_articulo   INTEGER REFERENCES articulo      ON DELETE CASCADE,
  id_evaluacion INTEGER REFERENCES evaluacion    ON DELETE CASCADE,
  id_par        INTEGER REFERENCES par_evaluador ON DELETE CASCADE
);

-- 4c. Mensajes sueltos: un correo que la dependencia envía a un par o a un autor eligiendo una plantilla de mensaje
--     (no pertenece a una evaluación, por eso no está en «correo»). Guarda el texto tal como se envió.
CREATE TABLE mensaje (
  id_mensaje    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_revista    SMALLINT     NOT NULL REFERENCES revista ON DELETE RESTRICT,  -- la revista desde la que sale (su remitente)
  id_plantilla  SMALLINT     REFERENCES plantilla ON DELETE SET NULL,
  id_par        INTEGER      REFERENCES par_evaluador ON DELETE CASCADE,
  id_autor      INTEGER      REFERENCES autor ON DELETE CASCADE,
  id_usuario    INTEGER      REFERENCES usuario ON DELETE SET NULL,
  destinatario  VARCHAR(150) NOT NULL,
  nombre        VARCHAR(200) NOT NULL,
  asunto        VARCHAR(300) NOT NULL,
  cuerpo        TEXT         NOT NULL,
  fecha_envio   TIMESTAMPTZ  NOT NULL DEFAULT now(),
  resultado     VARCHAR(8)   NOT NULL DEFAULT 'en-cola'
                  CHECK (resultado IN ('en-cola','enviado','rebotado','fallido')),
  CONSTRAINT ck_mensaje_un_destinatario CHECK ((id_par IS NULL) <> (id_autor IS NULL))
);
CREATE INDEX ix_mensaje_revista ON mensaje (id_revista, fecha_envio);

-- 5. El artículo puede cambiar de revista en cualquier etapa y la base de pares es común a las dos
--    revistas, por eso no hay reglas de cambio de revista en la base.
 
-- 6. Índices
CREATE UNIQUE INDEX ux_un_desempate     ON evaluacion (id_articulo) WHERE es_desempate;
CREATE UNIQUE INDEX ux_plantilla_en_uso ON plantilla (id_revista, tipo) WHERE tipo IS NOT NULL;  -- una en uso por tipo y revista
CREATE INDEX ix_articulo_ojs          ON articulo (id_revista, numero_ojs);  -- avisa cuando un número de OJS se repite
CREATE INDEX ix_articulo_listado      ON articulo (id_revista, estado, fecha_postulacion);
CREATE INDEX ix_articulo_publicacion  ON articulo (id_revista, volumen, numero);
CREATE INDEX ix_articulo_autor_autor  ON articulo_autor (id_autor);
CREATE INDEX ix_par_area              ON par_evaluador (lower(area));
CREATE INDEX ix_evaluacion_par        ON evaluacion (id_par);
CREATE INDEX ix_alerta_sin_respuesta  ON evaluacion (fecha_asignacion)
  WHERE estado_par = 'invitado';
CREATE INDEX ix_constancia_pendiente  ON evaluacion (id_articulo)
  WHERE estado_par = 'entrego' AND NOT constancia_emitida;
CREATE INDEX ix_correo_evaluacion     ON correo (id_evaluacion, fecha_envio);
CREATE INDEX ix_revision_articulo     ON revision_inicial_comite (id_articulo, fecha);
CREATE INDEX ix_auditoria_registro    ON auditoria (tabla_afectada, id_registro);
CREATE INDEX ix_auditoria_contexto    ON auditoria USING gin (detalle jsonb_path_ops);
 
-- 7. Vistas: datos que la página muestra y que se calculan (no se guardan)
CREATE VIEW v_par AS                     -- Pares evaluadores, ficha del par, bloqueados
SELECT p.id_par, p.id_revista, p.nombre, p.universidad, p.area,
       (p.fecha_bloqueo IS NOT NULL)                         AS bloqueado,
       count(e.id_evaluacion) FILTER (WHERE e.estado_par = 'entrego') AS entregadas,
       count(e.id_evaluacion) FILTER (WHERE e.estado_par = 'invitado') AS sin_responder,
       count(e.id_evaluacion) FILTER (WHERE e.estado_par IN ('invitado','acepto')) AS en_curso,
       (p.fecha_bloqueo IS NULL AND count(e.id_evaluacion)
          FILTER (WHERE e.estado_par IN ('invitado','acepto')) = 0) AS disponible,
       max(e.fecha_asignacion)                               AS ultima_participacion
FROM par_evaluador p
LEFT JOIN evaluacion e ON e.id_par = p.id_par
GROUP BY p.id_par;
 
CREATE VIEW v_constancia AS              -- Constancias: pendientes y emitidas
SELECT a.id_revista, e.id_evaluacion, a.numero_ojs, p.nombre AS par, e.fecha_evaluacion,
       e.constancia_emitida,
       (SELECT min(c.fecha_envio)
          FROM correo c
         WHERE c.id_evaluacion = e.id_evaluacion
           AND c.tipo = 'agradecimiento')                 AS emitida_el,
       EXISTS (SELECT 1 FROM auditoria au
                WHERE au.tabla_afectada = 'evaluacion'
                  AND au.id_registro = e.id_evaluacion::text
                  AND au.accion = 'migracion')                AS migrado
FROM evaluacion e
JOIN articulo a      ON a.id_articulo = e.id_articulo
JOIN par_evaluador p ON p.id_par = e.id_par
WHERE e.estado_par = 'entrego';
 
CREATE VIEW v_intentos AS                -- «2.º intento» y bloqueo automático
SELECT e.id_evaluacion, e.id_par, count(c.id_correo) AS intentos
FROM evaluacion e
LEFT JOIN correo c ON c.id_evaluacion = e.id_evaluacion
                  AND c.tipo = 'invitacion' AND c.resultado = 'enviado'
WHERE e.estado_par = 'invitado'
GROUP BY e.id_evaluacion, e.id_par;
