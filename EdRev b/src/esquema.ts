/*
 * esquema — pone al día una base de datos creada con una versión anterior, al arrancar la API. Todo es idempotente
 * (se puede ejecutar cuantas veces sea): si la base ya está al día no cambia nada. Una base nueva ya trae esto
 * mismo desde db/01_esquema.sql y db/02_datos_iniciales.sql; esto existe para que quien ya tenía el sistema
 * funcionando (en la máquina local o en el servidor) no tenga que ejecutar scripts a mano al actualizar.
 *
 * Cambios que aplica:
 * - las plantillas pueden ser de tipo «mensaje» (para enviar un correo a mano a un par o a un autor);
 * - la tabla `mensaje`, donde queda cada uno de esos correos;
 * - una plantilla «Mensaje general» de ejemplo en cada revista que todavía no tenga una;
 * - las plantillas de invitación o de agradecimiento que sobran (no son la que se envía sola) pasan a ser mensajes:
 *   cada revista queda con sus tres textos automáticos y el resto son mensajes que se eligen al enviar un correo;
 * - la constancia con el texto inicial anterior (sin editar) pasa al de la constancia de la dependencia, y la revista
 *   IRE toma su nombre oficial («Revista Investigium IRE: Ciencias Sociales y Humanas»).
 */
import { TEXTO_CONSTANCIA, TEXTO_CONSTANCIA_ANTERIOR } from './lib/textoConstancia.js'
import type { Cliente } from './db.js'

export async function asegurarEsquema(c: Cliente): Promise<void> {
  const { rows } = await c.query<{ def: string }>(
    `SELECT pg_get_constraintdef(oid) AS def FROM pg_constraint
      WHERE conrelid = 'plantilla'::regclass AND conname = 'plantilla_fin_check'`,
  )
  if (rows[0] && !rows[0].def.includes('mensaje')) {
    await c.query('ALTER TABLE plantilla DROP CONSTRAINT plantilla_fin_check')
    await c.query(
      `ALTER TABLE plantilla ADD CONSTRAINT plantilla_fin_check
         CHECK (fin IN ('invitacion','agradecimiento','constancia','mensaje'))`,
    )
  }
  await c.query(`
    CREATE TABLE IF NOT EXISTS mensaje (
      id_mensaje    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      id_revista    SMALLINT     NOT NULL REFERENCES revista ON DELETE RESTRICT,
      id_plantilla  SMALLINT     REFERENCES plantilla ON DELETE SET NULL,
      id_par        INTEGER      REFERENCES par_evaluador ON DELETE CASCADE,
      id_autor      INTEGER      REFERENCES autor ON DELETE CASCADE,
      id_usuario    INTEGER      REFERENCES usuario ON DELETE SET NULL,
      destinatario  VARCHAR(150) NOT NULL,
      nombre        VARCHAR(200) NOT NULL,
      asunto        VARCHAR(300) NOT NULL,
      cuerpo        TEXT         NOT NULL,
      fecha_envio   TIMESTAMPTZ  NOT NULL DEFAULT now(),
      resultado     VARCHAR(8)   NOT NULL DEFAULT 'en-cola'
                      CHECK (resultado IN ('en-cola','enviado','rebotado','fallido')),
      CONSTRAINT ck_mensaje_un_destinatario CHECK ((id_par IS NULL) <> (id_autor IS NULL))
    )`)
  await c.query('CREATE INDEX IF NOT EXISTS ix_mensaje_revista ON mensaje (id_revista, fecha_envio)')
  await c.query(
    `INSERT INTO plantilla (id_revista, nombre, clase, fin, tipo, asunto, cuerpo)
     SELECT r.id_revista, 'Mensaje general', 'correo', 'mensaje', NULL, 'Mensaje de {{revista}}',
            E'Apreciado(a) {{nombre}}:\\n\\nLe escribimos desde la Dependencia de Editorial de la {{revista}}.\\n\\nCordialmente,'
       FROM revista r
      WHERE NOT EXISTS (SELECT 1 FROM plantilla p WHERE p.id_revista = r.id_revista AND p.fin = 'mensaje')
        AND NOT EXISTS (SELECT 1 FROM plantilla p WHERE p.id_revista = r.id_revista AND p.nombre = 'Mensaje general')`,
  )
  // Cada invitación o agradecimiento guarda la plantilla que se eligió al enviarlo.
  await c.query('ALTER TABLE correo ADD COLUMN IF NOT EXISTS id_plantilla SMALLINT REFERENCES plantilla ON DELETE SET NULL')
  // El texto propio por envío ya no existe: se retiran sus columnas de las bases que las tenían.
  await c.query('ALTER TABLE correo DROP COLUMN IF EXISTS asunto_propio')
  await c.query('ALTER TABLE correo DROP COLUMN IF EXISTS cuerpo_propio')
  // La constancia con la disposición de la que entrega la dependencia: solo si todavía tiene el texto inicial anterior
  // sin cambios (una constancia que la Administradora ya editó se respeta).
  await c.query("UPDATE plantilla SET cuerpo = $1 WHERE fin = 'constancia' AND replace(cuerpo, chr(13), '') = $2", [
    TEXTO_CONSTANCIA,
    TEXTO_CONSTANCIA_ANTERIOR,
  ])
  // El nombre oficial de la revista IRE lleva dos puntos, como en sus constancias.
  await c.query(
    "UPDATE revista SET nombre = 'Revista Investigium IRE: Ciencias Sociales y Humanas' WHERE nombre = 'Revista Investigium IRE Ciencias Sociales y Humanas'",
  )
}
